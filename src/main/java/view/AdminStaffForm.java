    private void tblUsersMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblUsersMouseClicked
        int row = tblUsers.getSelectedRow();
        if (row >= 0) {
            txtUserId.setText(tableModel.getValueAt(row, 0).toString());
            txtUsername.setText(tableModel.getValueAt(row, 1).toString());
            txtUsername.setEditable(false); // Username is unique identifier
            txtFullName.setText(tableModel.getValueAt(row, 2).toString());
            cmbRole.setSelectedItem(tableModel.getValueAt(row, 3).toString());
            txtContact.setText(tableModel.getValueAt(row, 4) != null ? tableModel.getValueAt(row, 4).toString() : "");
            txtPassword.setText(""); // Leave empty unless modifying
        }
    }//GEN-LAST:event_tblUsersMouseClicked

