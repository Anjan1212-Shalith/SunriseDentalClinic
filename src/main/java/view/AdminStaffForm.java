    public void loadUserData() {
        tableModel.setRowCount(0);
        List<User> list = userDAO.getAllUsers();
        for (User u : list) {
            tableModel.addRow(new Object[]{
                    u.getUserId(),
                    u.getUsername(),
                    u.getFullName(),
                    u.getRole(),
                    u.getContactNo()
            });
        }
    }

    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        String username = txtUsername.getText().trim();
        String fullName = txtFullName.getText().trim();
        String role = (String) cmbRole.getSelectedItem();
        String contact = txtContact.getText().trim();
        String password = new String(txtPassword.getPassword()).trim();

        if (username.isEmpty() || fullName.isEmpty() || password.isEmpty() || contact.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill in all mandatory fields!", "Validation Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (!contact.matches("^0[0-9]{9}$")) {
            JOptionPane.showMessageDialog(this, "Contact number must be a 10-digit Sri Lankan phone number (e.g., 0771234567)!", "Validation Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (userDAO.usernameExists(username)) {
            JOptionPane.showMessageDialog(this, "Username '" + username + "' is already registered!", "Conflict Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }

        User newUser = new User(username, password, fullName, role, contact);
        boolean success = userDAO.registerUser(newUser);

        if (success) {
            JOptionPane.showMessageDialog(this, "Staff account for " + fullName + " (" + role + ") successfully created!", "Success", JOptionPane.INFORMATION_MESSAGE);
            loadUserData();
            btnClearActionPerformed(evt);
        } else {
            JOptionPane.showMessageDialog(this, "Failed to create staff account.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnSaveActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        String idStr = txtUserId.getText().trim();
        if (idStr.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please select a staff member from the table to update!", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int userId = Integer.parseInt(idStr);
        String username = txtUsername.getText().trim();
        String fullName = txtFullName.getText().trim();
        String role = (String) cmbRole.getSelectedItem();
        String contact = txtContact.getText().trim();
        String password = new String(txtPassword.getPassword()).trim();

        if (username.isEmpty() || fullName.isEmpty() || contact.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Full Name, Role, and Contact cannot be empty!", "Validation Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }

        User updatedUser = new User();
        updatedUser.setUserId(userId);
        updatedUser.setUsername(username);
        updatedUser.setFullName(fullName);
        updatedUser.setRole(role);
        updatedUser.setContactNo(contact);
        if (!password.isEmpty()) {
            updatedUser.setPassword(password);
        }

        boolean success = userDAO.updateUser(updatedUser);

        if (success) {
            JOptionPane.showMessageDialog(this, "Staff account for " + fullName + " updated successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
            loadUserData();
            btnClearActionPerformed(evt);
        } else {
            JOptionPane.showMessageDialog(this, "Failed to update staff account.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        String idStr = txtUserId.getText().trim();
        if (idStr.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please select a staff member from the table to delete!", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int userId = Integer.parseInt(idStr);
        String username = txtUsername.getText().trim();

        if ("admin".equalsIgnoreCase(username)) {
            JOptionPane.showMessageDialog(this, "The primary system Administrator account cannot be deleted!", "Security Restriction", JOptionPane.ERROR_MESSAGE);
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete staff account: " + username + "?", "Confirm Delete", JOptionPane.YES_NO_OPTION);
        if (confirm == JOptionPane.YES_OPTION) {
            boolean success = userDAO.deleteUser(userId);
            if (success) {
                JOptionPane.showMessageDialog(this, "Staff account deleted successfully.", "Deleted", JOptionPane.INFORMATION_MESSAGE);
                loadUserData();
                btnClearActionPerformed(evt);
            } else {
                JOptionPane.showMessageDialog(this, "Failed to delete user account.", "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

