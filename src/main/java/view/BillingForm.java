    private void onDiscountRateSelected() {
        try {
            double treatFee = Double.parseDouble(txtTreatmentFee.getText().trim());
            double consultFee = Double.parseDouble(txtConsultationFee.getText().trim());
            double subtotal = treatFee + consultFee;

            int index = cmbDiscountRate.getSelectedIndex();
            double discountAmt = 0.0;
            switch (index) {
                case 0: // 0% - No Discount
                    discountAmt = 0.0;
                    txtDiscount.setText("0.00");
                    txtDiscount.setEditable(false);
                    break;
                case 1: // 10% - Promotional
                    discountAmt = subtotal * 0.10;
                    txtDiscount.setText(String.format("%.2f", discountAmt));
                    txtDiscount.setEditable(false);
                    break;
                case 2: // 25% - Senior Citizen
                    discountAmt = subtotal * 0.25;
                    txtDiscount.setText(String.format("%.2f", discountAmt));
                    txtDiscount.setEditable(false);
                    break;
                case 3: // 50% - Staff Welfare
                    discountAmt = subtotal * 0.50;
                    txtDiscount.setText(String.format("%.2f", discountAmt));
                    txtDiscount.setEditable(false);
                    break;
                case 4: // Custom Amount (LKR)
                    txtDiscount.setEditable(true);
                    txtDiscount.requestFocus();
                    break;
            }

            btnCalculateActionPerformed(null);
        } catch (NumberFormatException ignored) {
        }
    }

    private void btnCalculateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalculateActionPerformed
        try {
            double treatFee = Double.parseDouble(txtTreatmentFee.getText().trim());
            double consultFee = Double.parseDouble(txtConsultationFee.getText().trim());
            double discount = Double.parseDouble(txtDiscount.getText().trim());

            double subtotal = treatFee + consultFee;
            double discountPercent = subtotal > 0 ? (discount / subtotal) * 100.0 : 0.0;

            // Stored procedure calculation (sp_CalculateBill)
            double total = billDAO.calculateBillProcedure(treatFee, consultFee, discountPercent);
            txtTotalAmount.setText(String.format("%.2f", total));

            generateReceiptPreviewText(treatFee, consultFee, discount, total);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Please enter valid numeric fee amounts!", "Input Warning", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_btnCalculateActionPerformed

    private void generateReceiptPreviewText(double treatFee, double consultFee, double discount, double total) {
        String apptNo = (String) cmbAppointmentNo.getSelectedItem();
        String patientName = txtPatientName.getText().trim();
        String treatment = txtTreatmentType.getText().trim();
        String status = (String) cmbPaymentStatus.getSelectedItem();
        String dateStr = new SimpleDateFormat("yyyy-MM-dd HH:mm:ss").format(new Date());

        String discountLabel = "Discount Applied";
        int discIdx = cmbDiscountRate.getSelectedIndex();
        if (discIdx == 1) discountLabel = "Discount (10% Promo)";
        else if (discIdx == 2) discountLabel = "Discount (25% Senior)";
        else if (discIdx == 3) discountLabel = "Discount (50% Staff)";
        else if (discIdx == 0) discountLabel = "Discount (0%)";

        StringBuilder sb = new StringBuilder();
        sb.append("=================================================================\n");
        sb.append("                    SUNRISE DENTAL CLINIC                        \n");
        sb.append("         No 45, Galle Road, Colombo 03, Sri Lanka                \n");
        sb.append("           Tel: +94 11 234 5678 | Web: sunrisedental.lk          \n");
        sb.append("=================================================================\n");
        sb.append(String.format(" Receipt Date    : %-30s\n", dateStr));
        sb.append(String.format(" Appointment No  : %-30s\n", apptNo != null ? apptNo : "N/A"));
        sb.append(String.format(" Patient Name    : %-30s (ID: %d)\n", patientName, currentPatientId));
        sb.append(String.format(" Treatment Type  : %-30s\n", treatment));
        sb.append("-----------------------------------------------------------------\n");
        sb.append(String.format(" %-40s : LKR %12.2f\n", "Dental Treatment Fee", treatFee));
        sb.append(String.format(" %-40s : LKR %12.2f\n", "Dentist Consultation Fee", consultFee));
        sb.append("-----------------------------------------------------------------\n");
        sb.append(String.format(" %-40s : LKR %12.2f\n", "Subtotal", treatFee + consultFee));
        sb.append(String.format(" %-40s : LKR %12.2f\n", discountLabel, discount));
        sb.append("=================================================================\n");
        sb.append(String.format(" NET TOTAL PAYABLE                        : LKR %12.2f\n", total));
        sb.append(String.format(" Payment Status                           : %s\n", status));
        sb.append("=================================================================\n");
        sb.append("              Thank you for trusting Sunrise Dental!             \n");
        sb.append("=================================================================\n");

        txaReceiptPreview.setText(sb.toString());
    }

    private void btnSaveBillActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveBillActionPerformed
        String apptNo = (String) cmbAppointmentNo.getSelectedItem();
        String patientName = txtPatientName.getText().trim();
        String status = (String) cmbPaymentStatus.getSelectedItem();

        if (apptNo == null || patientName.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please select an appointment before saving!", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            double treatFee = Double.parseDouble(txtTreatmentFee.getText().trim());
            double consultFee = Double.parseDouble(txtConsultationFee.getText().trim());
            double discount = Double.parseDouble(txtDiscount.getText().trim());
            double total = Double.parseDouble(txtTotalAmount.getText().trim());

            Bill bill = new Bill(apptNo, currentPatientId, patientName, treatFee, consultFee, discount, total, status);
            boolean success = billDAO.generateBill(bill);

            if (success) {
                JOptionPane.showMessageDialog(this, "Bill record successfully saved for " + apptNo + "!", "Success", JOptionPane.INFORMATION_MESSAGE);
                loadBillsData();
                if (parentDashboard instanceof Dashboard) {
                    ((Dashboard) parentDashboard).loadDashboardStatistics();
                }
            } else {
                JOptionPane.showMessageDialog(this, "Failed to save bill.", "Error", JOptionPane.ERROR_MESSAGE);
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Invalid numeric values!", "Warning", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_btnSaveBillActionPerformed

