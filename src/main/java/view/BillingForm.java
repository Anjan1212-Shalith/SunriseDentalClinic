    private void loadAppointmentsDropdown() {
        cmbAppointmentNo.removeAllItems();
        List<Appointment> list = appointmentDAO.getAllAppointments();
        for (Appointment a : list) {
            cmbAppointmentNo.addItem(a.getAppointmentNo());
        }
    }

    private void onAppointmentSelected() {
        String apptNo = (String) cmbAppointmentNo.getSelectedItem();
        if (apptNo == null) return;

        Appointment a = appointmentDAO.getAppointmentByNo(apptNo);
        if (a != null) {
            currentPatientId = a.getPatientId();
            txtPatientName.setText(a.getPatientName());
            txtTreatmentType.setText(a.getTreatmentType());

            double treatCost = dentistDAO.getTreatmentCost(a.getTreatmentType());
            txtTreatmentFee.setText(String.format("%.2f", treatCost));

            Dentist d = dentistDAO.getDentistByName(a.getDentistName());
            double consultFee = d != null ? d.getConsultationFee() : 2000.00;
            txtConsultationFee.setText(String.format("%.2f", consultFee));

            onDiscountRateSelected();
        }
    }

    public void loadBillsData() {
        tableModel.setRowCount(0);
        List<Bill> list = billDAO.getAllBills();
        for (Bill b : list) {
            tableModel.addRow(new Object[]{
                    b.getBillId(),
                    b.getAppointmentNo(),
                    b.getPatientId(),
                    b.getPatientName(),
                    String.format("%.2f", b.getTreatmentFee()),
                    String.format("%.2f", b.getConsultationFee()),
                    String.format("%.2f", b.getDiscount()),
                    String.format("%.2f", b.getTotalAmount())
            });
        }
    }

