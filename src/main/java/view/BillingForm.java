    private void btnPrintActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPrintActionPerformed
        if (txaReceiptPreview.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "No receipt to print!", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            boolean complete = txaReceiptPreview.print();
            if (complete) {
                JOptionPane.showMessageDialog(this, "Receipt sent to printer!", "Print Success", JOptionPane.INFORMATION_MESSAGE);
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Printing Error: " + e.getMessage(), "Print Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnPrintActionPerformed

    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        String keyword = txtSearch.getText().trim();
        if (keyword.isEmpty()) {
            loadBillsData();
            return;
        }

        tableModel.setRowCount(0);
        List<Bill> list = billDAO.searchBills(keyword);
        for (Bill b : list) {
            tableModel.addRow(new Object[]{
                    b.getBillId(),
                    b.getAppointmentNo(),
                    b.getPatientId(),
                    b.getPatientName(),
                    String.format("%.2f", b.getTreatmentFee()),
                    String.format("%.2f", b.getConsultationFee()),
                    String.format("%.2f", b.getDiscount()),
                    String.format("%.2f", b.getTotalAmount())
            });
        }
    }//GEN-LAST:event_btnSearchActionPerformed

