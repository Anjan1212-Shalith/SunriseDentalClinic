    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        String apptNo = txtAppointmentNo.getText().trim();
        Object patientObj = cmbPatient.getSelectedItem();
        Object dentistObj = cmbDentist.getSelectedItem();
        Object treatmentObj = cmbTreatment.getSelectedItem();
        String dateStr = txtDate.getText().trim();
        String timeSlot = (String) cmbTimeSlot.getSelectedItem();
        String status = (String) cmbStatus.getSelectedItem();
        String notes = txaNotes.getText().trim();

        if (patientObj == null || dentistObj == null || treatmentObj == null || dateStr.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill in all mandatory fields!", "Validation Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }

        PatientComboItem patientItem = (PatientComboItem) patientObj;
        DentistComboItem dentistItem = (DentistComboItem) dentistObj;
        TreatmentComboItem treatmentItem = (TreatmentComboItem) treatmentObj;

        Date sqlDate;
        try {
            sqlDate = Date.valueOf(dateStr);
        } catch (IllegalArgumentException e) {
            JOptionPane.showMessageDialog(this, "Invalid Date format! Use YYYY-MM-DD.", "Date Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        if (appointmentDAO.isDoubleBooked(dentistItem.name, sqlDate, timeSlot, null)) {
            JOptionPane.showMessageDialog(this,
                    "Conflict: " + dentistItem.name + " is already booked on " + sqlDate + " at " + timeSlot + "!",
                    "Double Booking Conflict",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        Appointment appt = new Appointment(apptNo, patientItem.id, patientItem.name, dentistItem.name, treatmentItem.name, sqlDate, timeSlot, status, notes);
        boolean success = appointmentDAO.createAppointment(appt);

        if (success) {
            JOptionPane.showMessageDialog(this, "Appointment " + apptNo + " confirmed for " + patientItem.name + "!", "Success", JOptionPane.INFORMATION_MESSAGE);
            loadAppointmentData();
            btnClearActionPerformed(evt);
            if (parentDashboard instanceof Dashboard) {
                ((Dashboard) parentDashboard).loadDashboardStatistics();
            }
        } else {
            JOptionPane.showMessageDialog(this, "Failed to schedule appointment.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnSaveActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        String apptNo = txtAppointmentNo.getText().trim();
        Object patientObj = cmbPatient.getSelectedItem();
        Object dentistObj = cmbDentist.getSelectedItem();
        Object treatmentObj = cmbTreatment.getSelectedItem();
        String dateStr = txtDate.getText().trim();
        String timeSlot = (String) cmbTimeSlot.getSelectedItem();
        String status = (String) cmbStatus.getSelectedItem();
        String notes = txaNotes.getText().trim();

        if (apptNo.isEmpty() || patientObj == null || dentistObj == null || treatmentObj == null) {
            JOptionPane.showMessageDialog(this, "Please select an appointment from the table to update!", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }

        PatientComboItem patientItem = (PatientComboItem) patientObj;
        DentistComboItem dentistItem = (DentistComboItem) dentistObj;
        TreatmentComboItem treatmentItem = (TreatmentComboItem) treatmentObj;

        Date sqlDate;
        try {
            sqlDate = Date.valueOf(dateStr);
        } catch (IllegalArgumentException e) {
            JOptionPane.showMessageDialog(this, "Invalid Date format! Use YYYY-MM-DD.", "Date Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        if (appointmentDAO.isDoubleBooked(dentistItem.name, sqlDate, timeSlot, apptNo)) {
            JOptionPane.showMessageDialog(this, "Conflict: Dentist already booked at this time slot!", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }

        Appointment appt = new Appointment(apptNo, patientItem.id, patientItem.name, dentistItem.name, treatmentItem.name, sqlDate, timeSlot, status, notes);
        boolean success = appointmentDAO.updateAppointment(appt);

        if (success) {
            JOptionPane.showMessageDialog(this, "Appointment updated successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
            loadAppointmentData();
            btnClearActionPerformed(evt);
        } else {
            JOptionPane.showMessageDialog(this, "Failed to update appointment.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        String apptNo = txtAppointmentNo.getText().trim();
        if (apptNo.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please select an appointment to delete!", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(this, "Are you sure you want to cancel appointment " + apptNo + "?", "Confirm Cancel", JOptionPane.YES_NO_OPTION);
        if (confirm == JOptionPane.YES_OPTION) {
            boolean success = appointmentDAO.deleteAppointment(apptNo);
            if (success) {
                JOptionPane.showMessageDialog(this, "Appointment cancelled.", "Deleted", JOptionPane.INFORMATION_MESSAGE);
                loadAppointmentData();
                btnClearActionPerformed(evt);
                if (parentDashboard instanceof Dashboard) {
                    ((Dashboard) parentDashboard).loadDashboardStatistics();
                }
            } else {
                JOptionPane.showMessageDialog(this, "Failed to delete appointment.", "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

