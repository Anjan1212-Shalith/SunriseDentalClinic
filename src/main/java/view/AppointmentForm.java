    private static class PatientComboItem {
        int id;
        String name;
        String contact;

        public PatientComboItem(int id, String name, String contact) {
            this.id = id;
            this.name = name;
            this.contact = contact;
        }

        @Override
        public String toString() {
            return name + " (ID: " + id + " | " + contact + ")";
        }
    }

    private static class DentistComboItem {
        String name;
        String spec;
        double consultationFee;

        public DentistComboItem(String name, String spec, double fee) {
            this.name = name;
            this.spec = spec;
            this.consultationFee = fee;
        }

        @Override
        public String toString() {
            return name + " (" + spec + ")";
        }
    }

    private static class TreatmentComboItem {
        String name;
        double cost;

        public TreatmentComboItem(String name, double cost) {
            this.name = name;
            this.cost = cost;
        }

        @Override
        public String toString() {
            return name + " (LKR " + String.format("%.0f", cost) + ")";
        }
    }
