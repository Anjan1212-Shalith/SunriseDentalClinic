    private void tblAppointmentsMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblAppointmentsMouseClicked
        int row = tblAppointments.getSelectedRow();
        if (row >= 0) {
            txtAppointmentNo.setText(tableModel.getValueAt(row, 0).toString());
            int patId = Integer.parseInt(tableModel.getValueAt(row, 1).toString());
            String dentistName = tableModel.getValueAt(row, 3).toString();
            String treatName = tableModel.getValueAt(row, 4).toString();
            txtDate.setText(tableModel.getValueAt(row, 5).toString());
            cmbTimeSlot.setSelectedItem(tableModel.getValueAt(row, 6).toString());
            cmbStatus.setSelectedItem(tableModel.getValueAt(row, 7).toString());

            for (int i = 0; i < cmbPatient.getItemCount(); i++) {
                Object item = cmbPatient.getItemAt(i);
                if (item instanceof PatientComboItem && ((PatientComboItem) item).id == patId) {
                    cmbPatient.setSelectedIndex(i);
                    break;
                }
            }

            for (int i = 0; i < cmbDentist.getItemCount(); i++) {
                Object item = cmbDentist.getItemAt(i);
                if (item instanceof DentistComboItem && ((DentistComboItem) item).name.equals(dentistName)) {
                    cmbDentist.setSelectedIndex(i);
                    break;
                }
            }

            for (int i = 0; i < cmbTreatment.getItemCount(); i++) {
                Object item = cmbTreatment.getItemAt(i);
                if (item instanceof TreatmentComboItem && ((TreatmentComboItem) item).name.equals(treatName)) {
                    cmbTreatment.setSelectedIndex(i);
                    break;
                }
            }

            updateCostPreview();
        }
    }//GEN-LAST:event_tblAppointmentsMouseClicked

