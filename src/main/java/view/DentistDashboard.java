    private void loadTreatmentRecommendations() {
        cmbRecommendedTreatment.removeAllItems();
        cmbRecommendedTreatment.addItem("-- No Future Treatment Required --");
        Map<String, Double> treatments = dentistDAO.getAllTreatmentsWithCosts();
        for (String treat : treatments.keySet()) {
            cmbRecommendedTreatment.addItem(treat);
        }
    }

    private void loadDoctorSchedule() {
        tableModel.setRowCount(0);
        String doctorName = currentDentist.getFullName();
        List<Appointment> list = appointmentDAO.getAppointmentsByDentist(doctorName);
        
        // Fallback: If no direct doctor match, load all active appointments
        if (list.isEmpty()) {
            list = appointmentDAO.getAllAppointments();
        }

        for (Appointment a : list) {
            tableModel.addRow(new Object[]{
                    a.getAppointmentNo(),
                    a.getPatientId(),
                    a.getPatientName(),
                    a.getTreatmentType(),
                    a.getAppointmentDate(),
                    a.getAppointmentTime(),
                    a.getStatus()
            });
        }
    }

