    private void tblDoctorAppointmentsMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblDoctorAppointmentsMouseClicked
        int row = tblDoctorAppointments.getSelectedRow();
        if (row >= 0) {
            selectedAppointmentNo = tableModel.getValueAt(row, 0).toString();
            selectedPatientId = Integer.parseInt(tableModel.getValueAt(row, 1).toString());
            String patientName = tableModel.getValueAt(row, 2).toString();
            String currentTreatment = tableModel.getValueAt(row, 3).toString();

            lblSelectedAppt.setText("Selected Appointment: " + selectedAppointmentNo + " (" + currentTreatment + ")");
            lblSelectedPatient.setText("Patient: " + patientName + " (Patient ID: " + selectedPatientId + ")");

            Appointment appt = appointmentDAO.getAppointmentByNo(selectedAppointmentNo);
            if (appt != null) {
                txaDiagnosis.setText(appt.getDiagnosis() != null ? appt.getDiagnosis() : "");
                if (appt.getRecommendedTreatment() != null && !appt.getRecommendedTreatment().isEmpty()) {
                    cmbRecommendedTreatment.setSelectedItem(appt.getRecommendedTreatment());
                } else {
                    cmbRecommendedTreatment.setSelectedIndex(0);
                }
                if (appt.getFollowUpAdvice() != null && !appt.getFollowUpAdvice().isEmpty()) {
                    cmbFollowUp.setSelectedItem(appt.getFollowUpAdvice());
                } else {
                    cmbFollowUp.setSelectedIndex(0);
                }
            }
        }
    }//GEN-LAST:event_tblDoctorAppointmentsMouseClicked

    private void btnSaveFeedbackActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveFeedbackActionPerformed
        if (selectedAppointmentNo.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please select an appointment from the left queue first!", "Selection Required", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String diagnosis = txaDiagnosis.getText().trim();
        String recommendedTreatment = cmbRecommendedTreatment.getSelectedIndex() > 0 ? (String) cmbRecommendedTreatment.getSelectedItem() : "";
        String followUp = (String) cmbFollowUp.getSelectedItem();

        if (diagnosis.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter clinical observations / diagnosis notes before saving!", "Validation Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }

        boolean success = appointmentDAO.saveDentistFeedback(selectedAppointmentNo, diagnosis, recommendedTreatment, followUp);
        if (success) {
            JOptionPane.showMessageDialog(this,
                    "Consultation feedback successfully recorded for " + selectedAppointmentNo + "!\n" +
                    "Status marked as Completed.\n" +
                    "Front-desk staff can now view future recommendations for this patient.",
                    "Clinical Feedback Saved",
                    JOptionPane.INFORMATION_MESSAGE);
            loadDoctorSchedule();
            clearForm();
        } else {
            JOptionPane.showMessageDialog(this, "Failed to save consultation feedback.", "Database Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnSaveFeedbackActionPerformed

